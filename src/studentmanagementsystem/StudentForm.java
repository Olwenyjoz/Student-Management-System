        pst.setString(5, course.getSelectedItem().toString());
        pst.setString(6, year.getSelectedItem().toString());
        pst.setString(7, phonenumber.getText());
        pst.setString(8, email.getText());
        pst.setDouble(9, Double.parseDouble(feebalance.getText()));
        pst.setString(10, status.getSelectedItem().toString());
