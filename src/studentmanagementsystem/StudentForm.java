   private boolean validateInputs() {

    if (regnumber.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Registration Number is required.");
        regnumber.requestFocus();
        return false;
    }

    if (firstname.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "First Name is required.");
        firstname.requestFocus();
        return false;
    }

    if (lastname.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Last Name is required.");
        lastname.requestFocus();
        return false;
    }

    if (gender.getSelectedIndex() == 0) {
        JOptionPane.showMessageDialog(this, "Please select Gender.");
        gender.requestFocus();
        return false;
    }

    if (course.getSelectedIndex() == 0) {
        JOptionPane.showMessageDialog(this, "Please select Course.");
        course.requestFocus();
        return false;
    }

    if (year.getSelectedIndex() == 0) {
        JOptionPane.showMessageDialog(this, "Please select Year Level.");
        year.requestFocus();
        return false;
    }

    if (phonenumber.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Phone Number is required.");
        phonenumber.requestFocus();
        return false;
    }

    if (!phonenumber.getText().matches("\\d{10}")) {
        JOptionPane.showMessageDialog(this,
                "Phone Number must contain exactly 10 digits.");
        phonenumber.requestFocus();
        return false;
    }

    if (email.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Email is required.");
        email.requestFocus();
        return false;
    }

    if (!email.getText().matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+$")) {
        JOptionPane.showMessageDialog(this,
                "Enter a valid email address.");
        email.requestFocus();
        return false;
    }

    if (feebalance.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Fee Balance is required.");
        feebalance.requestFocus();
        return false;
    }

    try {
        Double.parseDouble(feebalance.getText());

        if (Double.parseDouble(feebalance.getText()) < 0) {
            JOptionPane.showMessageDialog(this,
                    "Fee Balance cannot be negative.");
            feebalance.requestFocus();
            return false;
        }

    } catch (NumberFormatException ex) {

        JOptionPane.showMessageDialog(this,
                "Fee Balance must be numeric.");

        feebalance.requestFocus();

        return false;

    }

    return true;

    }

   
