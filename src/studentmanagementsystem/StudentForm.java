        pst = cn.prepareStatement(
                "INSERT INTO students "
                + "(registration_number, first_name, last_name, gender, course, "
                + "year_level, phone, email, feebalance, status, photo) "
                + "VALUES (?,?,?,?,?,?,?,?,?,?,?)");

